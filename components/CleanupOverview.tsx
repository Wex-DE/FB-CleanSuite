import React from 'react';
import { CheckCircle2, Clock, AlertCircle, HelpCircle, BarChart3, ShieldCheck, FileText } from 'lucide-react';
import { WorkerState } from '@/server/types';

interface CleanupOverviewProps {
  worker: WorkerState | null;
  totalDiscovered: number;
  pageName?: string;
}

export const CleanupOverview: React.FC<CleanupOverviewProps> = ({ worker, totalDiscovered, pageName }) => {
  const stats = worker?.stats || {
    total: totalDiscovered,
    pending: totalDiscovered,
    deleted: 0,
    failed: 0,
    skipped: 0,
    unknown: 0,
  };

  const total = stats.total > 0 ? stats.total : totalDiscovered;
  const percentage = total > 0 ? Math.min(100, Math.round((stats.deleted / total) * 100)) : 0;
  const remaining = Math.max(0, total - stats.deleted);

  // SVG circular progress parameters
  const radius = 38;
  const circumference = 2 * Math.PI * radius;
  const strokeDashoffset = circumference - (percentage / 100) * circumference;

  const isRunning = worker?.status === 'running';

  const exportAuditReport = () => {
    const formattedDate = new Date().toLocaleString('en-US', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });

    const reportContent = `# FB CleanSuite — Post Cleanup Audit Report
Generated: ${formattedDate}
Target Facebook Page: ${pageName || 'Selected Page'}

---

## 📊 Summary Statistics
- Total Posts Discovered: ${total.toLocaleString()}
- Successfully Deleted: ${stats.deleted.toLocaleString()} (${percentage}%)
- Remaining in Queue: ${remaining.toLocaleString()}
- Failed Deletions: ${stats.failed.toLocaleString()}
- Skipped / Unknown: ${(stats.skipped + stats.unknown).toLocaleString()}

## 🛡️ Security & Protocol Information
- API Endpoint: Meta Graph API v21.0 (Signed token authentication)
- Rate Limit Protection: Dynamic Adaptive Backoff Guard
- Session State: ${worker?.status.toUpperCase() || 'IDLE'}
- Verification Check: All HTTP status responses logged and verified

---
Report automatically generated by FB CleanSuite.
`;

    const blob = new Blob([reportContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `fb_cleansuite_report_${(pageName || 'page').replace(/\s+/g, '_')}_${new Date().toISOString().slice(0, 10)}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="rounded-2xl border border-slate-200/80 dark:border-white/[0.08] bg-white/95 dark:bg-slate-900/70 p-6 backdrop-blur-xl shadow-sm dark:shadow-xl flex flex-col justify-between transition-all">
      <div>
        {/* Card Header */}
        <div className="flex items-center justify-between gap-3 pb-5 border-b border-slate-200/80 dark:border-white/[0.08]">
          <div className="flex items-center gap-2.5">
            <div className="rounded-xl bg-blue-500/10 p-2 text-blue-600 dark:text-blue-400 border border-blue-500/20">
              <BarChart3 className="w-4 h-4" />
            </div>
            <div>
              <h2 className="text-sm font-bold text-slate-900 dark:text-white tracking-tight">
                Cleanup Overview
              </h2>
              <p className="text-[11px] text-slate-500 dark:text-slate-400">
                Live statistics &amp; progress breakdown
              </p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            {stats.deleted > 0 && (
              <button
                type="button"
                onClick={exportAuditReport}
                className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-lg border border-slate-200 dark:border-white/10 bg-white dark:bg-slate-900 text-[11px] font-semibold text-slate-700 dark:text-slate-300 hover:bg-slate-100 dark:hover:bg-slate-800 transition shadow-sm active:scale-95"
                title="Download full cleanup audit report"
              >
                <FileText className="h-3.5 w-3.5 text-blue-500" />
                <span>Audit Report</span>
              </button>
            )}

            {isRunning ? (
              <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-[11px] font-semibold bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border border-emerald-500/20 shadow-sm">
                <span className="h-1.5 w-1.5 rounded-full bg-emerald-500 animate-ping" />
                Cleanup in progress
              </span>
            ) : worker?.status === 'paused' ? (
              <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-[11px] font-semibold bg-amber-500/10 text-amber-600 dark:text-amber-400 border border-amber-500/20 shadow-sm">
                <span className="h-1.5 w-1.5 rounded-full bg-amber-500" />
                Cleanup paused
              </span>
            ) : (
              <span className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-[11px] font-semibold bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-400 border border-slate-200 dark:border-slate-700/60 shadow-sm">
                <span className="h-1.5 w-1.5 rounded-full bg-slate-400" />
                Ready to clean
              </span>
            )}
          </div>
        </div>

        {/* Circular Chart & Total Posts Row */}
        <div className="flex flex-col sm:flex-row items-center gap-6 py-6">
          {/* Radial Progress Circle */}
          <div className="relative flex-shrink-0 flex items-center justify-center">
            <svg className="w-28 h-28 transform -rotate-90">
              {/* Background track circle */}
              <circle
                cx="56"
                cy="56"
                r={radius}
                className="text-slate-100 dark:text-slate-800/80 stroke-current"
                strokeWidth="7"
                fill="transparent"
              />
              {/* Active progress circle */}
              <circle
                cx="56"
                cy="56"
                r={radius}
                className="text-blue-500 transition-all duration-700 stroke-current"
                strokeWidth="7"
                strokeDasharray={circumference}
                strokeDashoffset={strokeDashoffset}
                strokeLinecap="round"
                fill="transparent"
              />
            </svg>
            <div className="absolute flex flex-col items-center justify-center text-center">
              <span className="text-xl font-bold font-mono text-slate-900 dark:text-white leading-none">
                {percentage}%
              </span>
              <span className="text-[10px] text-slate-500 dark:text-slate-400 font-medium mt-1">
                Completed
              </span>
            </div>
          </div>

          {/* Right Metrics Block */}
          <div className="flex-1 w-full space-y-4">
            <div>
              <div className="text-3xl font-extrabold font-mono text-slate-900 dark:text-white tracking-tight">
                {total.toLocaleString()}
              </div>
              <div className="text-xs font-semibold text-slate-500 dark:text-slate-400 mt-0.5">
                Total Posts Discovered
              </div>
            </div>

            {/* 4 Clean Metric Badges */}
            <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5 text-xs">
              {/* Deleted */}
              <div className="rounded-xl border border-emerald-500/25 bg-emerald-500/10 p-3 flex flex-col justify-between">
                <div className="flex items-center justify-between text-emerald-600 dark:text-emerald-400">
                  <span className="text-[10px] font-bold uppercase tracking-wider">Deleted</span>
                  <CheckCircle2 className="h-3.5 w-3.5" />
                </div>
                <div className="font-extrabold font-mono text-lg text-emerald-600 dark:text-emerald-400 mt-1">
                  {stats.deleted.toLocaleString()}
                </div>
              </div>

              {/* Remaining */}
              <div className="rounded-xl border border-blue-500/25 bg-blue-500/10 p-3 flex flex-col justify-between">
                <div className="flex items-center justify-between text-blue-600 dark:text-blue-400">
                  <span className="text-[10px] font-bold uppercase tracking-wider">Remaining</span>
                  <Clock className="h-3.5 w-3.5" />
                </div>
                <div className="font-extrabold font-mono text-lg text-blue-600 dark:text-blue-400 mt-1">
                  {remaining.toLocaleString()}
                </div>
              </div>

              {/* Failed */}
              <div className="rounded-xl border border-rose-500/25 bg-rose-500/10 p-3 flex flex-col justify-between">
                <div className="flex items-center justify-between text-rose-600 dark:text-rose-400">
                  <span className="text-[10px] font-bold uppercase tracking-wider">Failed</span>
                  <AlertCircle className="h-3.5 w-3.5" />
                </div>
                <div className="font-extrabold font-mono text-lg text-rose-600 dark:text-rose-400 mt-1">
                  {stats.failed.toLocaleString()}
                </div>
              </div>

              {/* Skipped */}
              <div className="rounded-xl border border-amber-500/25 bg-amber-500/10 p-3 flex flex-col justify-between">
                <div className="flex items-center justify-between text-amber-600 dark:text-amber-400">
                  <span className="text-[10px] font-bold uppercase tracking-wider">Skipped</span>
                  <HelpCircle className="h-3.5 w-3.5" />
                </div>
                <div className="font-extrabold font-mono text-lg text-amber-600 dark:text-amber-400 mt-1">
                  {(stats.skipped + stats.unknown).toLocaleString()}
                </div>
              </div>
            </div>
          </div>
        </div>
      </div>

      {/* Bottom Horizontal Progress Bar */}
      <div className="pt-4 border-t border-slate-200/80 dark:border-white/[0.08] space-y-2">
        <div className="h-2 w-full overflow-hidden rounded-full bg-slate-100 dark:bg-slate-950">
          <div
            className="h-full rounded-full bg-blue-600 transition-all duration-700 shadow-sm"
            style={{ width: `${percentage}%` }}
          />
        </div>
        <div className="flex justify-between items-center text-[11px] text-slate-500 dark:text-slate-400">
          <span>{stats.deleted.toLocaleString()} of {total.toLocaleString()} posts permanently deleted</span>
          <span className="font-mono font-bold text-slate-700 dark:text-slate-300">{percentage}%</span>
        </div>
      </div>
    </div>
  );
};
